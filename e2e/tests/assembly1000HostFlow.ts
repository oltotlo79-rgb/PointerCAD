interface GateEvent {
  readonly attachment: number;
  readonly documentId: string;
  readonly generation: number;
  readonly stage: string;
  readonly reason: string | null;
  readonly count: number | null;
}

/** The bounded gate record of attachAssembly.ts, validated field by field (no window type is redeclared here). */
async function readGateEvents(page: Page): Promise<readonly GateEvent[]> {
  return page.evaluate(() => {
    const read: unknown = Reflect.get(window, 'pcadAssemblyRecomputeGates');
    if (typeof read !== 'function') throw new Error('組立の再計算の記録 pcadAssemblyRecomputeGates が見つかりません。');
    const value: unknown = read();
    const events: unknown = value !== null && typeof value === 'object' ? Reflect.get(value, 'events') : null;
    if (!Array.isArray(events)) throw new Error('組立の再計算の記録に events がありません。');
    return events.map((event: unknown) => {
      if (event === null || typeof event !== 'object') throw new Error('組立の再計算の記録の 1 件が壊れています。');
      const field = (name: string): unknown => Reflect.get(event, name);
      const attachment = field('attachment'), documentId = field('documentId'), generation = field('generation');
      const stage = field('stage'), reason = field('reason'), count = field('count');
      if (typeof attachment !== 'number' || typeof documentId !== 'string' || typeof generation !== 'number'
        || typeof stage !== 'string' || (reason !== null && typeof reason !== 'string') || (count !== null && typeof count !== 'number')) {
        throw new Error('組立の再計算の記録の欄の型が違います。');
      }
      return { attachment, documentId, generation, stage, reason, count };
    });
  });
}

/** The gates of the last published assembly recompute: its outcome, admitted generated sources and message count. */
async function lastPublication(page: Page): Promise<{ readonly outcome: string | null; readonly sources: number | null;
  readonly messages: number | null }> {
  const events = await readGateEvents(page);
  const published = events.filter((event) => event.stage === 'publication-admitted').at(-1);
  if (published === undefined) throw new Error('組立の再計算が表示へ渡った記録がありません。');
  const same = (stage: string) => events.filter((event) => event.stage === stage && event.attachment === published.attachment
    && event.documentId === published.documentId && event.generation === published.generation).at(-1);
  return { outcome: published.reason, sources: same('source-owners-admitted')?.count ?? null, messages: same('solver')?.count ?? null };
}

async function readAssemblyMeshBytes(page: Page): Promise<{ readonly source: number; readonly instances: number; readonly gpu: number }> {
  return page.evaluate(() => {
    const read: unknown = Reflect.get(window, 'pcadViewportMemoryStats');
    const value: unknown = typeof read === 'function' ? read() : null;
    if (value === null || typeof value !== 'object') throw new Error('ビューポートのメッシュの記録 pcadViewportMemoryStats が見つかりません。');
    const source: unknown = Reflect.get(value, 'assemblySourceBackingBytes');
    const instances: unknown = Reflect.get(value, 'assemblyInstanceBytes');
    const gpu: unknown = Reflect.get(value, 'gpuMeshBytes');
    if (typeof source !== 'number' || typeof instances !== 'number' || typeof gpu !== 'number') throw new Error('メッシュの記録の欄の型が違います。');
    return { source, instances, gpu };
  });
}

function near(actual: readonly number[] | undefined, expected: readonly number[], tolerance: number): boolean {
  return actual !== undefined && actual.length === expected.length
    && expected.every((value, axis) => Math.abs((actual[axis] ?? Number.NaN) - value) <= tolerance);
}

/** Components whose resolved or displayed placement is not the written one (empty when all 1000 are). */
function misplaced(stats: AssemblyBrowserStats, which: 'resolved' | 'displayed'): string[] {
  return stats.components.flatMap((component, index) => {
    const placement = component[which];
    return near(placement?.position, hostPositionOf(index), POSITION_MM) && near(placement?.rotation, hostStoredRotationOf(index), ROTATION)
      ? [] : [`${component.name} ${which}`];
  });
}

function sourcesByName(stats: AssemblyBrowserStats): Map<string, string> {
  return new Map(stats.components.map((component) => [component.name, component.sourceRef]));
}

/** Drawn after an open: the viewport holds assembly meshes and completed a render after the open began. */
async function waitDrawn(page: Page, label: string, rendersBefore: number): Promise<void> {
  await expect.poll(async () => {
    const bytes = await readAssemblyMeshBytes(page);
    return bytes.source > 0 && bytes.instances > 0 && bytes.gpu > 0;
  }, { message: `${label}: assembly meshes held by the viewport` }).toBe(true);
  await expect.poll(async () => (await readViewportRenderStats(page)).completedRenders, { message: `${label}: drawn after the open` })
    .toBeGreaterThan(rendersBefore);
}

