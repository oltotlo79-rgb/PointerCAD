/** r143: drive slider groups 0 and 1 one after the other; only the driven member moves, 998 never do. */
async function driveTwoGroups(page: Page, initial: AssemblyBrowserStats): Promise<void> {
  const motion = page.getByRole('group', { name: '組み立ての動き' });
  const translationOf = async (jointId: string): Promise<number | undefined> => (await readAssemblyStats(page)).jointValues
    .find((entry) => entry.key === `${jointId}${String.fromCharCode(0)}translation`)?.value;
  let previous = byName(initial);
  for (const [group, travel] of DRIVES) {
    const member = `member-${String(group)}`, index = HOST_NAMES.indexOf(member);
    const [x, y, z] = hostPositionOf(index);
    const jointRow = treeSectionRows(page, 'ジョイント').nth(group).locator('.pcad-tree__select');
    await jointRow.click();
    await expect(jointRow).toHaveAttribute('aria-pressed', 'true');
    const input = motion.locator('.pcad-assembly-motion__joint input[type="number"]');
    await expect(input).toHaveCount(1);
    await input.fill(String(travel));
    await expect.poll(() => translationOf(hostJointId(group))).toBeCloseTo(travel, 5);
    // The joint value is store state; the displayed placement follows it asynchronously (r142 display-settled wait).
    await expect.poll(async () => byName(await readAssemblyStats(page)).get(member)?.displayed?.position[2]).toBeCloseTo(z + travel, 9);
    const after = byName(await readAssemblyStats(page));
    const moved = after.get(member);
    expect(near(moved?.displayed?.position, [x, y, z + travel], POSITION_MM), `${member} at its anchor + (0, 0, ${String(travel)})`).toBe(true);
    expect(near(moved?.displayed?.rotation, hostStoredRotationOf(index), ROTATION), `${member} keeps its turn`).toBe(true);
    expect(near(moved?.resolved?.position, hostPositionOf(index), POSITION_MM), `${member} document placement unchanged`).toBe(true);
    // The other 999 keep exactly the placement shown before this drive.
    const changed = [...previous].filter(([name, component]) => name !== member
      && JSON.stringify(after.get(name)?.displayed) !== JSON.stringify(component.displayed)).map(([name]) => name);
    expect(changed, `others after driving ${member}`).toEqual([]);
    previous = after;
  }
  const driven = new Set(DRIVES.map(([group]) => `member-${String(group)}`));
  const start = byName(initial);
  const untouched = [...previous].filter(([name, component]) => !driven.has(name)
    && JSON.stringify(component.displayed) === JSON.stringify(start.get(name)?.displayed));
  expect(untouched.length, 'components untouched by both drives').toBe(HOST_TOTAL - driven.size);
}

/** The saved file: the 1000 written definitions (shape signatures of the table) and placements; no drive is saved. */
async function expectSavedFile(bytes: Uint8Array, shown: ReadonlyMap<string, string>): Promise<void> {
  const read = await readDocumentBundle(bytes, 'assembly');
  if (!read.ok || read.bundle.kind !== 'assembly') throw new Error(read.ok ? '組立の保存ではありません。' : read.error.message);
  const document = read.bundle.document, library = partLibraryOfBundle(read.bundle);
  expect(hostDefinitionProblems(document, library), 'saved definitions and placements').toEqual([]);
  const signatures = document.components.map((component) => {
    const definition = component.source.kind === 'part' ? library.parts.get(component.source.partRef) : undefined;
    const shape = definition === undefined ? null : definitionShapeOf(definition);
    return shape === null ? `${component.name}: no host shape` : oracleSignature(shapeOracleOf(shape));
  });
  expect(signatures, 'saved shape signatures').toEqual(HOST_NAMES.map((_, index) => oracleSignature(hostShapeOracle(index))));
  expect(new Set(signatures).size, 'distinct saved signatures').toBe(HOST_TOTAL);
  expect(new Map(document.components.map((component) => [component.name,
    component.source.kind === 'part' ? component.source.partRef : component.source.kind])), 'saved definitions are the shown ones')
    .toEqual(shown);
}

/** Elapsed wall time of each stage, printed as soon as the stage ends (a later failure keeps the earlier lines). */
function record(stages: Record<string, number>, name: string, startedAt: number): void {
  stages[name] = Date.now() - startedAt;
  console.log(`[区間の実測] ${name}=${String(stages[name])}`);
}
async function stage<T>(stages: Record<string, number>, name: string, run: () => Promise<T>): Promise<T> {
  const startedAt = Date.now();
  const value = await run();
  record(stages, name, startedAt);
  return value;
}

/**
 * The load sections of the latest assembly recomputes (attachAssembly.ts pcadAssemblyLoadTimings: release of the previous
 * document, the part loop with its kernel and availability round trips, resolve, constraints, publication), rounded to
 * whole milliseconds. Diagnostic metadata for the W02 bottleneck choice; nothing is judged from it.
 */
async function readLoadTimings(page: Page): Promise<unknown> {
  return page.evaluate(() => {
    const read: unknown = Reflect.get(window, 'pcadAssemblyLoadTimings');
    const value: unknown = typeof read === 'function' ? read() : null;
    const timings: unknown = value !== null && typeof value === 'object' ? Reflect.get(value, 'timings') : null;
    const inFlight: unknown = value !== null && typeof value === 'object' ? Reflect.get(value, 'inFlight') : null;
    if (!Array.isArray(timings)) return null;
    const rounded = (timing: unknown): unknown => timing === null || typeof timing !== 'object' ? timing
      : Object.fromEntries(Object.entries(timing).map(([key, field]) => [key, typeof field === 'number' ? Math.round(field) : field]));
    return { last: timings.slice(-2).map(rounded), inFlight: rounded(inFlight) };
  });
}

/**
 * Where one part's kernel round trip goes, from the bounded phase records of the bridge (main) and the kernel Worker
 * (pcadRuntimePhases, E2E build): mean milliseconds per dispatch over the last dispatches both sides still hold.
 * Diagnostic only (the W02 bottleneck choice); nothing is judged from it.
 */
async function readPhaseBreakdown(page: Page): Promise<unknown> {
  return page.evaluate(async () => {
    const read: unknown = Reflect.get(window, 'pcadRuntimePhases');
    if (typeof read !== 'function') return null;
    const observation: unknown = await read();
    if (observation === null || typeof observation !== 'object') return null;
    const recordsOf = (side: string): { phase: string; dispatchId: string; epochMs: number; monoMs: number }[] => {
      const value: unknown = Reflect.get(observation, side);
      const records: unknown = value !== null && typeof value === 'object' ? Reflect.get(value, 'records') : null;
      if (!Array.isArray(records)) return [];
      return records.flatMap((entry: unknown) => {
        if (entry === null || typeof entry !== 'object') return [];
        const phase: unknown = Reflect.get(entry, 'phase'), dispatchId: unknown = Reflect.get(entry, 'dispatchId');
        const epochMs: unknown = Reflect.get(entry, 'epochMs'), monoMs: unknown = Reflect.get(entry, 'monoMs');
        return typeof phase === 'string' && typeof dispatchId === 'string' && typeof epochMs === 'number' && typeof monoMs === 'number'
          ? [{ phase, dispatchId, epochMs, monoMs }] : [];
      });
    };
    const main = recordsOf('main'), worker = recordsOf('worker');
    const first = (records: typeof main, dispatchId: string, phase: string) =>
      records.find((entry) => entry.dispatchId === dispatchId && entry.phase === phase);
    const sums: Record<string, number> = {};
    let dispatches = 0, cancelChecks = 0;
    for (const dispatched of main.filter((entry) => entry.phase === 'dispatch')) {
      const id = dispatched.dispatchId;
      const start = first(worker, id, 'native-build-start'), built = first(worker, id, 'native-build-return');
      const preclone = first(worker, id, 'reply-preclone'), raw = first(main, id, 'raw-received');
      const adopted = first(main, id, 'adopted'), acknowledged = first(main, id, 'receiver-acknowledged');
      if (start === undefined || built === undefined || preclone === undefined || raw === undefined
        || adopted === undefined || acknowledged === undefined) continue;
      dispatches += 1;
      cancelChecks += worker.filter((entry) => entry.dispatchId === id && entry.phase === 'geometry-cancel-check').length;
      const add = (name: string, ms: number): void => { sums[name] = (sums[name] ?? 0) + ms; };
      add('dispatchToBuild', start.epochMs - dispatched.epochMs);
      add('build', built.monoMs - start.monoMs);
      add('buildToPreclone', preclone.monoMs - built.monoMs);
      add('precloneToReceived', raw.epochMs - preclone.epochMs);
      add('receivedToAdopted', adopted.monoMs - raw.monoMs);
      add('adoptedToAcknowledged', acknowledged.monoMs - adopted.monoMs);
      add('total', acknowledged.monoMs - dispatched.monoMs);
    }
    return { dispatches, cancelChecksPerDispatch: dispatches === 0 ? null : cancelChecks / dispatches,
      meanMs: Object.fromEntries(Object.entries(sums).map(([name, ms]) => [name, Math.round(ms / Math.max(1, dispatches) * 10) / 10])) };
  });
}

/** Main-thread long tasks (over 50 ms) while a stage runs, from a page PerformanceObserver. Diagnostic only. */
async function watchLongTasks(page: Page): Promise<() => Promise<unknown>> {
  await page.evaluate(() => {
    const totals = { count: 0, totalMs: 0, maxMs: 0 };
    const observer = new PerformanceObserver((list) => {
      for (const entry of list.getEntries()) {
        totals.count += 1; totals.totalMs += entry.duration; totals.maxMs = Math.max(totals.maxMs, entry.duration);
      }
    });
    observer.observe({ type: 'longtask' });
    Reflect.set(window, 'pcadEx12LongTasks', { totals, observer });
  });
  return () => page.evaluate(() => {
    const held: unknown = Reflect.get(window, 'pcadEx12LongTasks');
    if (held === null || typeof held !== 'object') return null;
    const observer: unknown = Reflect.get(held, 'observer'), totals: unknown = Reflect.get(held, 'totals');
    if (observer instanceof PerformanceObserver) observer.disconnect();
    if (totals === null || typeof totals !== 'object') return null;
    return Object.fromEntries(Object.entries(totals).map(([key, value]) => [key, typeof value === 'number' ? Math.round(value) : value]));
  });
}

/**
 * The host's open route; when its recompute does not succeed, the reasons in the status bar (distinct lines with their
 * counts, from the title of .pcad-statusbar__text as recompute.ts reads the progress), the gate reasons of the
 * last recompute and its load sections are printed before the same error is rethrown, so a failed open names its cause
 * (diagnosis only; the failure is never turned into a pass).
 */
async function openReportingReasons(page: Page, path: string, app: ElectronApplication | undefined, label: string): Promise<void> {
  try {
    await openSaveFlowFile(page, path, app);
  } catch (error: unknown) {
    const title = await page.locator('.pcad-statusbar__text').getAttribute('title', { timeout: 5_000 }).catch(() => null);
    const counts = new Map<string, number>();
    for (const line of (title ?? '').split(String.fromCharCode(10))) if (line !== '') counts.set(line, (counts.get(line) ?? 0) + 1);
    console.log(`[${label}の失敗の内訳] ${JSON.stringify([...counts])}`);
    const gates = await readGateEvents(page).catch(() => []);
    console.log(`[${label}の失敗の関門] ${JSON.stringify(gates.slice(-12).map((event) => [event.stage, event.reason, event.count]))}`);
    throw error;
  }
}

/** Open and draw with the diagnostics printed for the bottleneck choice (sections, kernel phases, main long tasks). */
async function openAndDraw(page: Page, path: string, app: ElectronApplication | undefined, label: string,
  stages: Record<string, number>): Promise<number> {
  const beforeRenders = (await readViewportRenderStats(page)).completedRenders;
  const longTasks = await watchLongTasks(page);
  const startedAt = Date.now();
  try {
    await stage(stages, `${label}Ms`, () => openReportingReasons(page, path, app, label));
    await waitDrawn(page, label, beforeRenders);
    record(stages, `${label}ToDrawnMs`, startedAt);
    return Date.now() - startedAt;
  } finally {
    // Printed after a failed open too: the kernel phases and main long tasks still name where the time went.
    console.log(`[${label}の区間の内訳] ${JSON.stringify({ sections: await readLoadTimings(page).catch(() => null),
      kernelPhases: await readPhaseBreakdown(page).catch(() => null), mainLongTasks: await longTasks().catch(() => null) })}`);
  }
}

/*
 * Interference (requirements §5.2: progress and cancel, all-path time over 5 runs, volume accuracy and release kept).
 * anchor-2 / member-2 share (600, 0, 0) and the same 4 mrad turn about z, so their common volume does not depend on the
 * turn: the cylinder of definition 4 (r = 2.4 / 2 = 1.2, h = 5 from z = 0) inside the holed box of definition 5
 * (6 x 2.5 x 8 about its centre, through hole r = min(6, 2.5) / 4 = 0.625 along z) is the ring of radii 1.2 and 0.625
 * over z = 0..4 (the ring fits inside |y| <= 1.25): 4 pi (1.2^2 - 0.625^2) mm^3. The panel shows 3 decimals
 * (interferenceView.ts formatInterferenceVolume).
 */
const INTERFERENCE_RUNS = 5;
const RING_PAIR = ['anchor-2', 'member-2'] as const;
const RING_VOLUME_MM3 = 4 * Math.PI * (1.2 ** 2 - 0.625 ** 2);

/*
 * How long one run is followed before it is recorded as unfinished and stopped through the panel's close (the store
 * then answers the running request's cancel check). Six times the 10 s limit: an unfinished run already fails the
 * judgement, and stopping it keeps the later stages (cancel display, reopen) measurable within the test's own limit.
 */
const INTERFERENCE_FOLLOW_MS = 60_000;

interface InterferenceRun { readonly ms: number; readonly completed: boolean; readonly progressSeen: boolean;
  readonly rows: readonly string[]; readonly summary: string; readonly error: string | null }

/** One run from the press (pointerdown, page clock) to the painted result summary, with the rows it shows. */
async function runInterference(page: Page): Promise<InterferenceRun> {
  const button = page.getByRole('group', { name: '組む' }).getByRole('button', { name: '干渉を調べる', exact: true });
  await button.evaluate((element) => {
    Reflect.deleteProperty(window, 'pcadEx12Interference');
    element.addEventListener('pointerdown', () => {
      const started = performance.now(), state = { progressSeen: false };
      const done = (): boolean => {
        const panel = document.querySelector('.pcad-interference');
        if (panel === null) return false;
        if (panel.querySelector('.pcad-interference__progress') !== null) { state.progressSeen = true; return false; }
        return panel.querySelector('.pcad-interference__summary') !== null || panel.querySelector('[role="alert"]') !== null;
      };
      const observer = new MutationObserver(() => {
        if (!done()) return;
        observer.disconnect();
        requestAnimationFrame(() => { Reflect.set(window, 'pcadEx12Interference', { ms: performance.now() - started, progressSeen: state.progressSeen }); });
      });
      observer.observe(document.body, { subtree: true, childList: true, characterData: true });
    }, { once: true });
  });
  await button.click();
  const pressedAt = Date.now();
  let completed = true;
  try {
    await expect.poll(() => page.evaluate(() => Reflect.get(window, 'pcadEx12Interference') !== undefined),
      { timeout: INTERFERENCE_FOLLOW_MS, message: 'interference result painted' }).toBe(true);
  } catch {
    completed = false;
  }
  if (!completed) {
    const followedMs = Date.now() - pressedAt;
    const progressSeen = await page.locator('.pcad-interference__progress').count() > 0;
    await page.locator('.pcad-interference__close').click();
    await expect(page.locator('.pcad-interference')).toHaveCount(0);
    return { ms: followedMs, completed: false, progressSeen, rows: [], summary: '', error: null };
  }
  const measured = await page.evaluate(() => {
    const value: unknown = Reflect.get(window, 'pcadEx12Interference');
    const ms: unknown = value !== null && typeof value === 'object' ? Reflect.get(value, 'ms') : null;
    const progressSeen: unknown = value !== null && typeof value === 'object' ? Reflect.get(value, 'progressSeen') : null;
    return { ms: typeof ms === 'number' ? ms : Number.NaN, progressSeen: progressSeen === true };
  });
  const panel = page.locator('.pcad-interference');
  // Each row is the pair (span: 'a × b') and its volume (strong: interferenceView.ts formatInterferenceVolume).
  const rows = await panel.locator('.pcad-interference__row').evaluateAll((elements) => elements.map((element) =>
    `${element.querySelector('span')?.textContent ?? ''} | ${element.querySelector('strong')?.textContent ?? ''}`));
  const summary = await panel.locator('.pcad-interference__summary').innerText().catch(() => '');
  const alert = panel.locator('[role="alert"]');
  const error = await alert.count() === 0 ? null : await alert.innerText();
  return { ...measured, completed: true, rows, summary, error };
}

/**
 * Cancel display (requirements §5.2: 200 ms target, 1,000 ms practical limit): a third open of the saved 1000-definition
 * file is cancelled with the status bar's 中止 while it computes; measured inside the page from the press to the painted
 * 『計算を中止しました。』 (the scriptLimitsFlow.ts method), then the latest generation must end cancelled.
 */
async function cancelDisplayMs(page: Page, path: string, app: ElectronApplication | undefined): Promise<number> {
  if (app !== undefined) await openTarget(app, path);
  const chooser = app === undefined ? page.waitForEvent('filechooser') : null;
  const token = await beginRecompute(page);
  await fileAction(page, '開く').click();
  if (chooser !== null) await (await chooser).setFiles(path);
  const cancel = page.locator('.pcad-statusbar__cancel');
  await expect(cancel).toBeVisible({ timeout: 60_000 });
  await cancel.evaluate((element) => {
    Reflect.deleteProperty(window, 'pcadEx12CancelMs');
    element.addEventListener('pointerdown', () => {
      const started = performance.now();
      const observer = new MutationObserver(() => {
        if (!(document.querySelector('.pcad-statusbar')?.textContent ?? '').includes('計算を中止しました。')) return;
        observer.disconnect();
        requestAnimationFrame(() => { Reflect.set(window, 'pcadEx12CancelMs', performance.now() - started); });
      });
      observer.observe(document.body, { subtree: true, childList: true, characterData: true });
    }, { once: true });
  });
  await cancel.click();
  await expect.poll(() => page.evaluate(() => typeof Reflect.get(window, 'pcadEx12CancelMs') === 'number'),
    { timeout: 30_000, message: 'cancel shown' }).toBe(true);
  const ms = await page.evaluate(() => { const value: unknown = Reflect.get(window, 'pcadEx12CancelMs'); return typeof value === 'number' ? value : Number.NaN; });
  await waitForRecomputeOutcome(page, token, 'cancelled');
  await expect(page.locator('.pcad-statusbar__text')).toHaveText('計算を中止しました。');
  return ms;
}

/** 成功時もraw JSON実体を保持し、古い実行の証拠を上書きしない。 */
async function attachHostObservation(info: TestInfo, name: string, value: unknown): Promise<void> {
  const path = info.outputPath(name);
  await writeFile(path, JSON.stringify(value, null, 2), { flag: 'wx' });
  await info.attach(name, { path, contentType: 'application/json' });
}

/** ホスト操作は正の時間を必須とし、既存observeDurationへ渡す薄い正値確認を使う。 */
async function observeHostDuration(info: TestInfo, name: string, actualMs: number, targetMs: number,
  label: string): Promise<DurationObservation> {
  await attachHostObservation(info, `assembly-1000-${name}-duration-raw.json`, { actualMs,
    referenceTargetMs: targetMs, finitePositive: Number.isFinite(actualMs) && actualMs > 0 });
  const observation = observePositiveDuration(actualMs, targetMs, label);
  await attachHostObservation(info, `assembly-1000-${name}-duration.json`, observation);
  return observation;
}

export async function assembly1000HostFlow(page: Page, info: TestInfo, app: ElectronApplication | undefined): Promise<void> {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const stages: Record<string, number> = {};
  // 取消と干渉の失敗は従来どおり最後に判定する。参考4観測は実測と達否を別に保存する。
  const durationObservations: DurationObservation[] = [];
  const judgements: string[] = [];
  const judge = (label: string, check: () => unknown): void => {
    try { check(); } catch (error: unknown) { judgements.push(`${label}: ${error instanceof Error ? error.message : String(error)}`); }
  };
  const source = info.outputPath('host1000.pcada');
  await stage(stages, 'fixtureMs', async () => { await writeFile(source, await assembly1000HostFile()); });
  // The viewport installs its render counter when it mounts (ViewportCanvas.tsx); read the count before the open.
  await page.waitForFunction(() => typeof Reflect.get(window, 'pcadViewportRenderStats') === 'function', undefined, { timeout: 15_000 });

  // 1. Open: 1000 components on 1000 own definitions, all generated and admitted, at their written placements, drawn.
  const openToDrawnMs = await openAndDraw(page, source, app, 'open', stages);
  durationObservations.push(await observeHostDuration(info, 'open', openToDrawnMs, HOST_LOAD_TARGET_MS, '異なる1,000定義の組立を開いて描画（初回）'));
  const initial = await expectLoaded(page, 'open');
  const shown = sourcesByName(initial);
  // Real drawing of the 1000 shapes under real mouse input (viewportRenderStats.ts, about 2 s of orbit and hover).
  const fps = await measureViewportFps(page);
  console.log(`[実測] 異なる1,000定義の組立の実描画: ${fps.fps.toFixed(1)} fps (${String(fps.completedRenders)}描画/${fps.elapsedMs.toFixed(1)}ms)`);
  await attachHostObservation(info, 'assembly-1000-fps-raw.json', fps);
  const viewportObservation = observeViewportRate(fps, '異なる1,000定義の組立（1,000部品）');
  await attachHostObservation(info, 'assembly-1000-fps-observation.json', viewportObservation);

  // 2. Drive the two slider groups separately; the other 998 never move.
  await stage(stages, 'driveTwoGroupsMs', () => driveTwoGroups(page, initial));

  // 3. Save: the file holds the written definitions and placements.
  const saved = info.outputPath('host1000-saved.pcada');
  const savedBytes = await stage(stages, 'saveMs', () => saveFlowFile(page, saved, app));
  durationObservations.push(await observeHostDuration(info, 'save', stages.saveMs ?? Number.NaN, HOST_SAVE_TARGET_MS, '異なる1,000定義の組立を保存'));
  await expectSavedFile(new Uint8Array(savedBytes), shown);

  // 4. Interference of the opened 1000 parts, 5 times: same result each time, progress shown, the ring volume exact
  //    (the drive moved groups 0 and 1 only; the ring pair is group 2).
  const runs: InterferenceRun[] = [];
  for (let run = 0; run < INTERFERENCE_RUNS; run += 1) {
    const measured = await runInterference(page);
    runs.push(measured);
    console.log(`[実測] 干渉 ${String(run + 1)}/${String(INTERFERENCE_RUNS)}: ${measured.ms.toFixed(1)} ms${measured.completed ? ''
      : `（${String(INTERFERENCE_FOLLOW_MS)}ms までに終わらず中止した）`}、組 ${String(measured.rows.length)}、${measured.summary}${measured.error === null ? '' : `、${measured.error}`}`);
    judge(`interference ${String(run + 1)}`, () => reportDuration(measured.ms, HOST_INTERFERENCE_TARGET_MS,
      '異なる1,000定義の組立の干渉（全経路）', 'interference'));
  }
  // Result checks over the runs that finished (an unfinished run already failed its time judgement above).
  const finished = runs.filter((run) => run.completed), firstRun = finished[0];
  if (firstRun !== undefined) {
    expect(firstRun.error, 'interference error').toBeNull();
    expect(finished.map((run) => [run.rows, run.summary]), 'the same interference result in every finished run')
      .toEqual(finished.map(() => [firstRun.rows, firstRun.summary]));
    const ringRow = firstRun.rows.find((row) => row.startsWith(`${RING_PAIR[0]} × ${RING_PAIR[1]} |`)
      || row.startsWith(`${RING_PAIR[1]} × ${RING_PAIR[0]} |`));
    expect(ringRow?.split(' | ')[1], `interference volume of ${RING_PAIR.join(' and ')}`).toBe(`${RING_VOLUME_MM3.toFixed(3)} mm³`);
  }
  expect(runs.some((run) => run.progressSeen), 'interference progress shown').toBe(true);
  console.log(`[干渉の結果] 完了 ${String(finished.length)}/${String(INTERFERENCE_RUNS)}、組 ${String(firstRun?.rows.length ?? 0)}、先頭 ${JSON.stringify(firstRun?.rows.slice(0, 3) ?? [])}、${firstRun?.summary ?? ''}`);

  // 5. Cancel display while an open of the saved file computes (the reopen below then opens it in full).
  const cancelMs = await cancelDisplayMs(page, saved, app);
  console.log(`[実測] 異なる1,000定義の組立の再計算の中止表示: ${cancelMs.toFixed(1)} ms`);
  judge('cancel', () => reportDuration(cancelMs, HOST_CANCEL_TARGET_MS, '異なる1,000定義の組立の再計算の中止表示'));

  // 6. Reopen: the same 1000 definitions, generated and drawn again, at the written placements (no drive restored).
  const reopenToDrawnMs = await openAndDraw(page, saved, app, 'reopen', stages);
  durationObservations.push(await observeHostDuration(info, 'reopen', reopenToDrawnMs, HOST_LOAD_TARGET_MS, '異なる1,000定義の組立を開き直して描画（再開）'));
  const reopened = await expectLoaded(page, 'reopen');
  expect(sourcesByName(reopened), 'reopened definitions are the saved ones').toEqual(shown);
  await info.attach('assembly-1000-host-reopened', { body: await page.screenshot(), contentType: 'image/png' });

  console.log(`[区間の実測] ${JSON.stringify({ host: app === undefined ? 'web' : 'electron', ...stages,
    fps: Math.round(fps.fps * 10) / 10, interferenceMs: runs.map((run) => Math.round(run.ms)), cancelMs: Math.round(cancelMs),
    savedBytes: savedBytes.length })}`);
  await attachHostObservation(info, 'assembly-1000-observations.json', { host: app === undefined ? 'web' : 'electron',
    stages, fps, interferenceRuns: runs, cancelMs, savedBytes: savedBytes.length,
    durationObservations, viewportObservation, errors, judgements });
  expect(errors).toEqual([]);
  expect(judgements, '1,000 部品の組立の性能の判定（要件 §5.2）').toEqual([]);
}
