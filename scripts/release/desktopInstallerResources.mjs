import { createHash } from 'node:crypto';
import { lstat, mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, isAbsolute, sep } from 'node:path';
import { createDesktopUninstallScript } from './desktopUninstall.mjs';
import { ELECTRON_EXECUTABLE_NOTICES } from './sbom.mjs';

/** Builder resources copied from apps/desktop/packaging (icon.ico/icon.png are named by electron-builder.yml). */
export const DESKTOP_BUILD_RESOURCES = Object.freeze(['installer.nsh', 'icon.ico', 'icon.png']);

export async function prepareDesktopInstallerResources(root, destination) {
  await mkdir(destination);
  for (const name of DESKTOP_BUILD_RESOURCES) {
    const bytes = await readFile(join(root, 'apps/desktop/packaging', name));
    if (bytes.length === 0) throw new Error('Empty desktop build resource: ' + name);
    await writeFile(join(destination, name), bytes, { flag: 'wx' });
  }
}

function assertInsideProject(root, folder) {
  const local = relative(root, folder);
  if (isAbsolute(local) || local === '' || local === '..' || local.startsWith('..' + sep)) throw new Error('Installer output must remain in the project');
  return local;
}

/** Called by builder after the actual Electron runtime has been assembled, before NSIS compilation. */
export async function writeDesktopUninstallFiles(root, appOutDir, resources) {
  const local = assertInsideProject(root, appOutDir);
  let cursor = root;
  for (const part of local.split(sep)) {
    cursor = join(cursor, part); if ((await lstat(cursor)).isSymbolicLink()) throw new Error('Installer output contains a link');
  }
  const names = []; let visited = 0;
  const walk = async (directory, depth) => {
    if (depth > 32) throw new Error('Installer output folders are too deep');
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      if (++visited > 40_000 || entry.isSymbolicLink()) throw new Error('Invalid installer output');
      const path = join(directory, entry.name);
      if (entry.isDirectory()) await walk(path, depth + 1);
      else if (entry.isFile()) names.push(relative(appOutDir, path).split(sep).join('/'));
      else throw new Error('Installer output contains a special file');
    }
  };
  await walk(appOutDir, 0);
  await writeFile(join(resources, 'uninstall-files.nsh'), createDesktopUninstallScript(names), { flag: 'wx' });
}

/**
 * Where package-desktop.mjs keeps, inside the candidate folder dist/<stage>/, a byte copy of the notices that
 * electron-builder left next to the executable. builder/ (the unpacked app) is not uploaded by release.yml, so the
 * release gate reads these copies instead.
 */
export const ELECTRON_NOTICE_COPY_FOLDER = 'executable-notices';

/**
 * Phrases of the original texts in the Electron archive (checked against electron 44.9.1's dist/LICENSE and
 * dist/LICENSES.chromium.html). app-builder-lib renames the archive's LICENSE to LICENSE.electron.txt and ignores a
 * failed rename, so a missing or foreign file is only caught here.
 */
const ELECTRON_NOTICE_PHRASES = Object.freeze({
  'LICENSE.electron.txt': ['Copyright (c) Electron contributors', 'Permission is hereby granted, free of charge, to any person obtaining',
    'The above copyright notice and this permission notice shall be included in all copies or substantial portions of the Software.',
    'THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND'],
  'LICENSES.chromium.html': ['<!-- Generated by licenses.py; do not edit. -->', '<title>Credits</title>',
    'Chromium software is made available as source code', '<span class="title">The Chromium Project</span>',
    '<span class="title">Node.js</span>', '<span class="title">V8 JavaScript Engine</span>'],
});

/**
 * Problems of the executable notices read from actual bytes: `notices` are `{ name, bytes }` (bytes null when the file
 * could not be read). Every name of ELECTRON_EXECUTABLE_NOTICES must be present once, non-empty UTF-8 and carry its
 * original-text phrases. `electronLicenseSha256` (optional, the SBOM's `electron/LICENSE` record) must equal the
 * SHA-256 of LICENSE.electron.txt. Returns an empty list when everything holds.
 */
export function electronExecutableNoticeProblems(notices, electronLicenseSha256 = null) {
  if (!Array.isArray(notices)) return ['Executable notices are not a list'];
  const problems = [];
  for (const notice of notices) {
    if (!ELECTRON_EXECUTABLE_NOTICES.includes(notice?.name)) problems.push('Unexpected executable notice: ' + String(notice?.name));
  }
  for (const name of ELECTRON_EXECUTABLE_NOTICES) {
    const found = notices.filter(notice => notice?.name === name);
    if (found.length !== 1) { problems.push((found.length === 0 ? 'Missing' : 'Duplicated') + ' executable notice: ' + name); continue; }
    const { bytes } = found[0];
    if (!(bytes instanceof Uint8Array) || bytes.byteLength === 0) { problems.push('Missing or empty executable notice: ' + name); continue; }
    let text;
    try { text = new globalThis.TextDecoder('utf-8', { fatal: true }).decode(bytes).replace(/\s+/gu, ' '); }
    catch { problems.push('Executable notice is not UTF-8: ' + name); continue; }
    const absent = ELECTRON_NOTICE_PHRASES[name].filter(phrase => !text.includes(phrase));
    if (absent.length > 0) problems.push(`Executable notice is not the original text: ${name} (missing: ${absent.join(' / ')})`);
    if (name === 'LICENSE.electron.txt' && electronLicenseSha256 !== null) {
      const actual = createHash('sha256').update(bytes).digest('hex');
      if (actual !== electronLicenseSha256) problems.push(`Executable notice differs from the SBOM electron/LICENSE record: ${name} ${actual} / ${electronLicenseSha256}`);
    }
  }
  return problems;
}

/**
 * Called by builder after the Electron runtime has been assembled, on Windows and Linux alike (before NSIS, the
 * portable executable and the AppImage are made from appOutDir): reads the notices next to the executable from their
 * actual bytes, refuses a missing, linked, empty or foreign one, and copies the same bytes to
 * <stage>/ELECTRON_NOTICE_COPY_FOLDER/. Never overwrites an existing copy.
 */
export async function keepElectronExecutableNotices(root, appOutDir, stage) {
  assertInsideProject(root, appOutDir); assertInsideProject(root, stage);
  const notices = [];
  for (const name of ELECTRON_EXECUTABLE_NOTICES) {
    const path = join(appOutDir, name), info = await lstat(path).catch(() => null);
    if (info === null || !info.isFile() || info.isSymbolicLink()) throw new Error('Missing executable notice next to the Electron executable: ' + name);
    notices.push({ name, bytes: await readFile(path) });
  }
  const problems = electronExecutableNoticeProblems(notices);
  if (problems.length > 0) throw new Error(problems.join('; '));
  const destination = join(stage, ELECTRON_NOTICE_COPY_FOLDER);
  await mkdir(destination);
  for (const notice of notices) await writeFile(join(destination, notice.name), notice.bytes, { flag: 'wx' });
}
