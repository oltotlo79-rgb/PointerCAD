function rowsOf(series: Series): readonly CatalogItemRow[] {
  return GROUPS[series].flatMap(([crossSection, entries]) => entries.map(([number, innerDiameter]): CatalogItemRow => ({
    key: `${series}${number}`,
    size: `${series}${number}`,
    standardLabel: 'JIS B 2401',
    densityMaterialId: 'rubber',
    dims: { innerDiameter, crossSection },
    evidence: O_RING_EVIDENCE,
    verification: 'manufacturer-catalog',
    verified: true,
    note: '',
  })));
}

function dimensionsOf(row: CatalogItemRow): ORingDimensions {
  return { innerDiameter: row.dims.innerDiameter ?? NaN, crossSection: row.dims.crossSection ?? NaN };
}

function familyOf(series: Series, id: string, kindKey: string): CatalogFamily {
  const partName = (row: CatalogItemRow): string => `O リング ${row.size}`;
  return {
    id,
    group: 'mechanical',
    kindKey,
    catalogRevision: 'o-ring-2026-11-r1',
    generatorRevision: 'o-ring-1',
    options: [],
    stock: 'count',
    diagram: 'oRing',
    rows: rowsOf(series),
    build: (row) => buildORingPart(dimensionsOf(row), partName(row)),
    nominalVolume: (row) => oRingVolume(dimensionsOf(row)),
    partName,
  };
}

