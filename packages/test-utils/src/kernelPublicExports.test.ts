it('keeps the kernel public export names at the reviewed boundary', () => {
  const file = fileURLToPath(new URL('../../kernel/src/index.ts', import.meta.url));
  const source = ts.createSourceFile(file, readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
  const names: string[] = [];
  for (const statement of source.statements) {
    if (!ts.isExportDeclaration(statement)) continue;
    if (statement.exportClause === undefined || !ts.isNamedExports(statement.exportClause)) throw new Error('Unexpected kernel export form');
    names.push(...statement.exportClause.elements.map(element => element.name.text));
  }
  expect(names.sort()).toEqual(expected);
});
